if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

# Ensure src module is importable
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from src.evaluation.metrics import (
    compute_all_metrics,
    evaluate_dataset,
    normalize_answer
)


def load_val_dataset(val_file_path: Path) -> List[Dict[str, Any]]:
    """Loads and standardizes validation dataset."""
    if not val_file_path.exists():
        raise FileNotFoundError(f"Validation file not found: {val_file_path}")

    with open(val_file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    parsed = []
    for item in data:
        item_id = item.get("id")
        img = item.get("image", "")
        cat = item.get("category", "General")

        # Extract question & ground truth from conversations
        convs = item.get("conversations", [])
        question = ""
        ground_truth = ""
        for turn in convs:
            if turn.get("from") == "human":
                question = turn.get("value", "").replace("<image>\n", "").replace("<image>", "").strip()
            elif turn.get("from") == "gpt":
                ground_truth = turn.get("value", "").strip()

        parsed.append({
            "id": item_id,
            "image": img,
            "category": cat,
            "question": question,
            "ground_truth": ground_truth
        })

    return parsed


def load_predictions(preds_file_path: Optional[Path]) -> Dict[str, str]:
    """
    Loads predictions from JSON file.
    Supports formats:
    - List of dicts: [{'id': '...', 'prediction': '...'}, ...]
    - Dict mapping: {'val_00001': 'prediction text', ...}
    """
    if not preds_file_path or not preds_file_path.exists():
        return {}

    with open(preds_file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    pred_map = {}
    if isinstance(data, dict):
        pred_map = data
    elif isinstance(data, list):
        for item in data:
            item_id = item.get("id")
            pred = item.get("prediction")
            if pred is None:
                # Try finding in conversations
                for turn in item.get("conversations", []):
                    if turn.get("from") == "gpt":
                        pred = turn.get("value", "")
            if item_id:
                pred_map[item_id] = str(pred) if pred is not None else ""

    return pred_map


def generate_markdown_report(results: Dict[str, Any], model_name: str = "Evaluated Model") -> str:
    """Formats benchmark results into clean GitHub markdown."""
    overall = results.get("overall", {})
    by_cat = results.get("by_category", {})
    total = results.get("total_samples", 0)

    lines = [
        f"# 📊 Medical VQA Evaluation Report — {model_name}",
        f"**Total Validation Samples:** {total}\n",
        "## 📈 Performance Summary by Category",
        "",
        "| Category | Samples | Exact Match (Acc) | BLEU-1 (Unigram) | BLEU-2 (Bigram) | ROUGE-L (F1) |",
        "|---|:---:|:---:|:---:|:---:|:---:|",
    ]

    for cat_name, metrics in sorted(by_cat.items()):
        samples = metrics.get("samples", 0)
        em = f"{metrics.get('exact_match', 0.0) * 100:.2f}%"
        b1 = f"{metrics.get('bleu_1', 0.0) * 100:.2f}%"
        b2 = f"{metrics.get('bleu_2', 0.0) * 100:.2f}%"
        rl = f"{metrics.get('rouge_l', 0.0) * 100:.2f}%"
        lines.append(f"| **{cat_name}** | {samples} | **{em}** | {b1} | {b2} | {rl} |")

    # Add Overall Row
    o_em = f"{overall.get('exact_match', 0.0) * 100:.2f}%"
    o_b1 = f"{overall.get('bleu_1', 0.0) * 100:.2f}%"
    o_b2 = f"{overall.get('bleu_2', 0.0) * 100:.2f}%"
    o_rl = f"{overall.get('rouge_l', 0.0) * 100:.2f}%"
    lines.append(f"| **OVERALL** | **{total}** | **{o_em}** | **{o_b1}** | **{o_b2}** | **{o_rl}** |")

    lines.append("\n---\n*Report automatically generated by `src/evaluation/evaluate.py`.*")
    return "\n".join(lines)


def run_evaluation(
    val_file: str = "data/processed/val.json",
    predictions_file: Optional[str] = None,
    output_dir: str = "results",
    model_name: str = "LLaVA-1.5-7B",
    mock_baseline: bool = False
) -> Dict[str, Any]:
    """Runs complete evaluation pipeline."""
    val_path = Path(val_file).resolve()
    out_path = Path(output_dir).resolve()
    out_path.mkdir(parents=True, exist_ok=True)

    print(f"=== Medical VQA Evaluation Runner ===")
    print(f"Validation File:  {val_path}")
    print(f"Output Directory: {out_path}")

    val_dataset = load_val_dataset(val_path)
    print(f"Loaded {len(val_dataset)} validation samples.")

    pred_map = {}
    if predictions_file:
        preds_path = Path(predictions_file).resolve()
        pred_map = load_predictions(preds_path)
        print(f"Loaded {len(pred_map)} predictions from {preds_path}")
    elif mock_baseline:
        print("[INFO] Generating mock baseline predictions for verification...")
        # Simulate simple mock predictions for pipeline testing
        for idx, item in enumerate(val_dataset):
            # 35% exact match baseline simulation
            if idx % 3 == 0:
                pred_map[item["id"]] = item["ground_truth"]
            else:
                pred_map[item["id"]] = "normal" if item["category"] == "Abnormality" else "ct scan"

    eval_records = []
    csv_rows = []

    for item in val_dataset:
        item_id = item["id"]
        pred_text = pred_map.get(item_id, "")
        gt_text = item["ground_truth"]
        cat = item["category"]

        metrics = compute_all_metrics(pred_text, gt_text)
        eval_records.append({
            "id": item_id,
            "prediction": pred_text,
            "ground_truth": gt_text,
            "category": cat
        })

        csv_rows.append({
            "id": item_id,
            "image": item["image"],
            "category": cat,
            "question": item["question"],
            "ground_truth": gt_text,
            "prediction": pred_text,
            "exact_match": metrics["exact_match"],
            "bleu_1": metrics["bleu_1"],
            "bleu_2": metrics["bleu_2"],
            "rouge_l": metrics["rouge_l"]
        })

    # Compute Aggregate Metrics
    summary_results = evaluate_dataset(eval_records)
    summary_results["model_name"] = model_name

    # 1. Save results/evaluation_summary.json
    summary_json_path = out_path / "evaluation_summary.json"
    with open(summary_json_path, "w", encoding="utf-8") as f:
        json.dump(summary_results, f, indent=2, ensure_ascii=False)
    print(f"\n[1/3] Saved summary JSON:   {summary_json_path}")

    # 2. Save results/evaluation_report.md
    md_report = generate_markdown_report(summary_results, model_name=model_name)
    report_md_path = out_path / "evaluation_report.md"
    with open(report_md_path, "w", encoding="utf-8") as f:
        f.write(md_report)
    print(f"[2/3] Saved Markdown report: {report_md_path}")

    # 3. Save results/per_sample_predictions.csv
    csv_path = out_path / "per_sample_predictions.csv"
    fieldnames = ["id", "image", "category", "question", "ground_truth", "prediction", "exact_match", "bleu_1", "bleu_2", "rouge_l"]
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(csv_rows)
    print(f"[3/3] Saved Per-Sample CSV:  {csv_path}")

    # Print Report to Console
    print("\n" + md_report + "\n")
    return summary_results


def main():
    parser = argparse.ArgumentParser(description="Evaluate Medical VQA predictions against validation set.")
    parser.add_argument("--val_file", type=str, default="data/processed/val.json", help="Path to val.json")
    parser.add_argument("--predictions_file", type=str, default=None, help="Path to predictions JSON")
    parser.add_argument("--output_dir", type=str, default="results", help="Directory to save evaluation artifacts")
    parser.add_argument("--model_name", type=str, default="LLaVA-1.5-7B (Zero-Shot)", help="Model name for report")
    parser.add_argument("--mock", action="store_true", help="Run mock evaluation if no predictions file given")
    args = parser.parse_args()

    run_evaluation(
        val_file=args.val_file,
        predictions_file=args.predictions_file,
        output_dir=args.output_dir,
        model_name=args.model_name,
        mock_baseline=args.mock or (args.predictions_file is None)
    )


if __name__ == "__main__":
    main()
