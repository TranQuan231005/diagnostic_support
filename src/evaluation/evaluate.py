"""
Medical VQA Evaluation Pipeline Script.

Evaluates model predictions against ground truth validation dataset.
Generates:
1. results/evaluation_summary.json (Structured metrics JSON)
2. results/evaluation_report.md (Markdown table for reports & slides)
3. results/per_sample_predictions.csv (Per-sample row log for error analysis)
"""

